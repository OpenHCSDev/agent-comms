"""Parity declarations own matrix generation and the cutover decision."""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, ClassVar

from ..declared_family import DeclaredFamily

if TYPE_CHECKING:
    from ..plan_phases import PlanPhase
    from ..todos import Todo


class ParityComparison(ABC):
    @property
    @abstractmethod
    def passed(self) -> bool: ...


@dataclass(frozen=True)
class UnverifiedParity(ParityComparison):
    """Missing behavior has no evidence from which to claim a pass."""

    reason: str = "The native/current workflow comparison has not run."
    passed: ClassVar[bool] = False


class ParityRow(
    DeclaredFamily, affix="ParityRow", discovery_package="agent_comms.commander_parity"
):
    number: ClassVar[int]
    capability: ClassVar[str]
    current: ClassVar[str]
    native: ClassVar[str]
    phases: ClassVar[tuple[type[PlanPhase], ...]]

    @classmethod
    def compare(cls, todos: Iterable[Todo]) -> ParityComparison:
        return UnverifiedParity()

    @classmethod
    def rows(cls) -> tuple[type[ParityRow], ...]:
        rows = tuple(sorted(cls.members_with(cls), key=lambda row: row.number))
        numbers = tuple(row.number for row in rows)
        if not numbers or min(numbers) < 1 or len(set(numbers)) != len(numbers):
            raise ValueError("Parity declarations require unique positive row numbers")
        return rows

    @classmethod
    def done(cls, todos: Iterable[Todo]) -> bool:
        history = tuple(todos)
        return all(row.compare(history).passed for row in cls.rows())

    @classmethod
    def matrix(cls) -> str:
        """Render declared facts only; no mutable completion column lives here."""
        lines = [
            "<!-- Generated by python -m agent_comms.commander_parity; edit row declarations. -->",
            "| # | Capability | Current commander | Native owner | Native phases |",
            "|---|---|---|---|---|",
        ]
        for row in cls.rows():
            owners = ", ".join(f"`{phase.declared_name}`" for phase in row.phases)
            lines.append(
                f"| {row.number} | {row.capability} | {row.current} | {row.native} | {owners} |"
            )
        return "\n".join(lines) + "\n"

    @classmethod
    def render_plan(cls, path: Path) -> str:
        """Replace a generated section, never decode prose as executable identity."""
        text = path.read_text()
        before, marker, remainder = text.partition("## Parity matrix\n")
        _, end, after = remainder.partition("\n**Dropped deliberately:**")
        if not marker or not end:
            raise ValueError("Plan has no bounded parity matrix section")
        return before + marker + "\n" + cls.matrix() + end + after
