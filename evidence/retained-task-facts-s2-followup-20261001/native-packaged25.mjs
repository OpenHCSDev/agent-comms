import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const packageRoot=process.argv[2], effects=resolve(process.argv[3]);
await mkdir(effects,{recursive:true,mode:0o700});
const {createWriteToolDefinition}=await import(pathToFileURL(`${packageRoot}/dist/core/tools/write.js`));
const {createEditToolDefinition}=await import(pathToFileURL(`${packageRoot}/dist/core/tools/edit.js`));
const input='\uFEFFvalue = "λ"\r\n';
const result=await createWriteToolDefinition(effects).execute('actual-write',{path:'artifact.py',content:input});
let bytes=await readFile(`${effects}/artifact.py`);
assert.deepEqual(bytes,Buffer.from(input));
assert.equal(result.details.agentCommsArtifact.digest.value,createHash('sha256').update(bytes).digest('hex'));
assert.equal(result.details.agentCommsArtifact.byte_count,bytes.length);
const edit=await createEditToolDefinition(effects).execute('actual-edit',{path:'artifact.py',edits:[{oldText:'λ',newText:'changed'}]});
bytes=await readFile(`${effects}/artifact.py`);
assert.equal(edit.details.agentCommsArtifact.digest.value,createHash('sha256').update(bytes).digest('hex'));
assert.equal(edit.details.agentCommsArtifact.byte_count,bytes.length);
const before=Buffer.from(bytes);
await assert.rejects(createEditToolDefinition(effects).execute('actual-failed',{path:'artifact.py',edits:[{oldText:'ABSENT',newText:'bad'}]}));
assert.deepEqual(await readFile(`${effects}/artifact.py`),before);
const custom=await createWriteToolDefinition(effects,{operations:{mkdir:async()=>{},writeFile:async(path,text)=>{await writeFile(path,text.toUpperCase());}}}).execute('actual-custom',{path:'custom.py',content:'custom'});
assert.equal(custom.details,undefined);
const controller=new AbortController();controller.abort();
await assert.rejects(createWriteToolDefinition(effects).execute('actual-aborted',{path:'aborted.py',content:'no'},controller.signal));
console.log(JSON.stringify({state:'PACKAGED_SDK_IMPORT_FENCE_WRITE_EDIT_PASS',packageRoot,original_write:result,original_edit:edit,failed_edit_original_unchanged:true,custom_result:custom,aborted_no_success:true,provider_calls:0,public_changes:[]}));
